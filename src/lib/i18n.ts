export function useTranslation() {
  const { language, toggleLanguage, setLanguage } = useLanguageStore();
  // 放弃 mounted 检测。zustand persist 恢复是同步的（先 rehydrate，再 render），
  // 所以客户端第一次渲染时 language 已经是正确值。SSR 时 zustand 初始值为 'zh'，与
  // 默认语言一致，不会 hydration mismatch。这解决了之前 mounted 模式导致英文环境下
  // 显示中文（或反之）的问题。
  const t = (key: string): string => {
    const dict = translations[language];
    return dict[key as keyof typeof dict] || key;
  };

  return { t, language, toggleLanguage, setLanguage };
}
