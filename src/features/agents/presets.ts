// Normalize whitespace (collapse runs, drop line-ending/trailing differences)
// before comparing.
const normalizePrompt = (s: string) => s.replace(/\s+/g, ' ').trim();

// Structured body = everything from the first markdown heading onward. Users
// personalize a preset's intro ("你是Amanda，公司的法务顾问…" / "你是「盛文」的小秘书…")
// but leave the body (## 核心职责 / 技能 / 原则 …) untouched, so the body — not the
// full text — is the reliable signal for which preset an agent was built from.
const bodyOf = (s: string): string => {
  const idx = s.search(/#{1,6}\s/);
  return normalizePrompt(idx >= 0 ? s.slice(idx) : s);
};

function findPreset(systemPrompt: string): AgentPreset | undefined {
  const target = normalizePrompt(systemPrompt);
  // 1. full (whitespace-normalized) match — un-personalized prompts
  const full = AGENT_PRESETS.find((p) => normalizePrompt(p.systemPrompt) === target);
  if (full) return full;
  // 2. body match — intro was personalized, structured body is intact
  const bodyTarget = bodyOf(systemPrompt);
  if (bodyTarget) {
    return AGENT_PRESETS.find((p) => bodyOf(p.systemPrompt) === bodyTarget);
  }
  return undefined;
}

export function matchPresetId(systemPrompt: string): string {
  return findPreset(systemPrompt)?.id ?? '';
}

export function matchPresetName(systemPrompt: string): string {
  return findPreset(systemPrompt)?.name ?? '';
}

/**
 * Inject the agent's name into a preset prompt's opening line so the persona is
 * personalized at selection time — e.g. name "kelly" turns
 * "你是公司的行政秘书，负责…" into "你是公司的行政秘书"kelly"，负责…".
 *
 * Every preset opens with "你是公司的[角色]，…", so the name is inserted right
 * before the first comma of the whole prompt (the role→职责 break), landing just
 * after the role title. Returns the prompt unchanged when the name is empty or
 * there is no comma to anchor on, so callers can always pipe through it.
 */
export function personalizePresetPrompt(prompt: string, name: string): string {
  const trimmed = name.trim();
  if (!trimmed) return prompt;
  const firstComma = prompt.indexOf('，');
  if (firstComma === -1) return prompt;
  return `${prompt.slice(0, firstComma)}“${trimmed}”${prompt.slice(firstComma)}`;
}
